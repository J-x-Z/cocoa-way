// Columns: zh-Hans, zh-Hant, ja, ko, de, fr, es, pt, ru. Match-based
// lookup needs no lazy map, allocation, lock, or locale work on UI reads.
macro_rules! core_catalog {
    ($($key:literal => [$($value:literal),+]),* $(,)?) => {
        #[cfg(test)]
        pub(super) const CORE: &[(&str, [&str; 9])] = &[$(($key, [$($value),+])),*];
        pub(super) fn core_translation(language: Language, text: &str) -> Option<&'static str> {
            if matches!(language, Language::System | Language::English) { return None; }
            let column = language as usize - Language::SimplifiedChinese as usize;
            match text { $($key => Some([$($value),+][column]),)* _ => None }
        }
    };
}

